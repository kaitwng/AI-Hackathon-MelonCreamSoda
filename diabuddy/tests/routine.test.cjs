const assert = require('node:assert/strict');
const c = require('../dist/routine.js');
const now = new Date(2026, 10, 14, 12, 0);
const day = c.dateKey(now);
const meal = {id:'m',versions:[{from:'2026-11-08',name:'Lunch',time:'11:00',reminder:'10:30',days:[0,1,2,3,4,5,6]}]};
const data = {meals:[meal],records:{}};
assert.equal(c.status({}, c.mealsFor(data,day)[0],day,now.getTime()), 'Awaiting check-in');
let r = c.actionRecord({},'snooze',now.getTime());
assert.equal(r.snoozeUntil,now.getTime()+300000); assert.equal(r.snoozes,1);
r = c.actionRecord(r,'help',now.getTime()); assert.equal(c.status(r,c.mealsFor(data,day)[0],day,now.getTime()),'Help requested');
r = c.actionRecord(r,'ack',now.getTime()+1); assert.equal(r.ackAt,now.getTime()+1);
r = c.actionRecord(r,'record',now.getTime()+2,'child');
assert.deepEqual(c.actionRecord(r,'record',now.getTime()+3,'parent'),r);
assert.equal(c.status(r,c.mealsFor(data,day)[0],day,now.getTime()),'Child-reported completion');
data.records[c.occurrence(meal,day)] = r;
const report=c.summary(data,now); assert.equal(report.length,7); assert.equal(report[6].recorded,1); assert.equal(report[6].help,1); assert.equal(report[6].snoozes,1); assert.equal(report[5].noRecord,1);
meal.versions.push({from:day,name:'Dinner',time:'18:00',reminder:'17:00',days:[0,1,2,3,4,5,6]});
assert.equal(c.mealsFor(data,'2026-11-13')[0].version.name,'Lunch'); assert.equal(c.mealsFor(data,day)[0].version.name,'Dinner');
assert.equal(c.summary({meals:[meal],records:{}},now)[6].pending,1);
const pin={attempts:0,lockUntil:0};for(let i=0;i<5;i++) c.attemptFailure(pin,1000);assert.equal(pin.lockUntil,61000);assert.equal(pin.attempts,0);
assert.deepEqual(JSON.parse(JSON.stringify(data)), data);
console.log('Routine model checks passed.');
