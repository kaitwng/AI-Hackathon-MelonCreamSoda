const assert = require('node:assert/strict');
const {request,decide} = require('../dist/family-rewards.js');
const reward = {id:'r',name:'Choose dinner tonight',cost:50};
assert.equal(request(49,reward,[],'a'),null);
assert.equal(request(100,{...reward,cost:-1},[],'a'),null);
const held = request(100,reward,[],'a');
assert.equal(held.balance,50);
assert.equal(held.requests[0].status,'pending');
assert.equal(request(held.balance,reward,held.requests,'b'),null);
const approved = decide(held.balance,held.requests,'a',true);
assert.equal(approved.balance,50);
assert.equal(approved.requests[0].status,'approved');
assert.equal(decide(approved.balance,approved.requests,'a',true),null);
const declined = decide(held.balance,held.requests,'a',false);
assert.equal(declined.balance,100);
assert.equal(declined.requests[0].status,'declined');
assert.equal(decide(declined.balance,declined.requests,'a',false),null);
assert.equal(held.requests[0].cost,50);
console.log('Family rewards checks passed.');
